/** Lockfiles: lidos apenas pela regra de dependências. */
const LOCKFILES = new Set([
  'package-lock.json',
  'npm-shrinkwrap.json',
  'composer.lock',
  'gemfile.lock',
  'poetry.lock',
  'uv.lock',
  'pubspec.lock',
]);

/** Arquivos ignorados mesmo com extensão conhecida. */
const IGNORED_FILES = new Set(['yarn.lock', 'pnpm-lock.yaml', 'bun.lock', 'go.sum', 'cargo.lock']);

export function detectLanguages(
  fileName: string,
  extraExtensions: Readonly<Record<string, Language>> = {},
): Language[] {
  const name = fileName.toLowerCase();
  if (IGNORED_FILES.has(name)) return [];
  if (LOCKFILES.has(name)) return ['lockfile'];
  const manifest = MANIFESTS[name];
  if (manifest) return [...manifest];
  if (/^requirements[\w.-]*\.txt$/.test(name)) return ['manifest'];
  if (/\.(?:cs|vb|fs)proj$/.test(name)) return ['xml', 'manifest'];
  if (/\.min\.(?:js|css)$|\.(?:bundle|chunk)\.js$|\.map$/.test(name)) return [];

  const dot = name.lastIndexOf('.');
  if (dot < 0) return [];
  const extension = name.slice(dot);
  const extra = extraExtensions[extension];
  if (extra) return [extra];
  return [...(EXTENSIONS[extension] ?? [])];
}

